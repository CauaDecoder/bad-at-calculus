//! Reproducible, single-source content contracts (ADR 0008).

use schemars::{schema::RootSchema, schema_for};
use ts_rs::TS;

use crate::assessment_check::*;
use crate::{assessment::*, content::*};

/// JSON Schema roots consumed by importers and structured-output clients.
pub fn schemas() -> Vec<(&'static str, RootSchema)> {
    vec![
        ("exercise", schema_for!(Exercise)),
        ("exercise-list", schema_for!(ExerciseList)),
        ("pack-manifest", schema_for!(PackManifest)),
        ("pack", schema_for!(Pack)),
        ("answer-spec", schema_for!(AnswerSpec)),
        ("assessment-check-request", schema_for!(CheckRequest)),
        ("assessment-check-response", schema_for!(CheckResponse)),
    ]
}

/// TypeScript declarations generated from exactly the same DTOs as the schemas.
pub fn typescript() -> String {
    let declarations = [
        serde_json::Value::decl(),
        Tolerance::decl(),
        Feedback::decl(),
        ExpressionForm::decl(),
        NumericAnswer::decl(),
        ExpressionAnswer::decl(),
        EquationAnswer::decl(),
        ScalarAnswerSpec::decl(),
        SetAnswer::decl(),
        TupleAnswer::decl(),
        MatrixAnswer::decl(),
        AnswerOption::decl(),
        ChoiceAnswer::decl(),
        MatchingAnswer::decl(),
        SelfGradedAnswer::decl(),
        AnswerSpec::decl(),
        GradableAnswer::decl(),
        CheckRequest::decl(),
        CheckStatus::decl(),
        SamplingResult::decl(),
        InputError::decl(),
        CheckResponse::decl(),
        Visibility::decl(),
        SourceKind::decl(),
        Source::decl(),
        ReferenceType::decl(),
        Reference::decl(),
        Asset::decl(),
        EngineRequest::decl(),
        Solution::decl(),
        Visualization::decl(),
        Part::decl(),
        Exercise::decl(),
        ListItem::decl(),
        ExerciseList::decl(),
        PackManifest::decl(),
        Pack::decl(),
    ];
    let mut output = String::from("// Generated by vx-api. Do not edit.\n\n");
    for declaration in declarations {
        output.push_str("// prettier-ignore\nexport ");
        output.push_str(&declaration);
        output.push('\n');
    }
    output
}
